import networkx as nx
from mmdnn.conversion.caffe.c2c.common import BasePass
from mmdnn.conversion.caffe.utils import get_kernel_dims, get_pad_dims, set_pad_dims


class UniquifyBlobNames(BasePass):
  
  def __init__(self):
    pass

    
  
  def get_new_blob_name(self, layername):

    if layername not in self.unique_blobs:
      self.unique_blobs.add(layername)
      return layername
    _idx = 0
    while True:
      if f"{layername}_{_idx}" not in self.unique_blobs:
        self.unique_blobs.add(f"{layername}_{_idx}")
        return f"{layername}_{_idx}"
      _idx += 1


  def do_transformation(self):
    '''
    Transformation to uniquify blobs.
    This functions iterates over all layers in the model and checks whether there are any common blobs in the top list and the bottom list. If so, it replaces the duplicate blobs in the top list with new blob names generated by get_new_blob_name. Before moving on to the next layer, the algorithm checks whether any blobs in the bottom list are coming from a top that was previously renamed, by checking the old_to_new_tensor_name_mapping. If so they are replaced by the new blob names.
    '''
    self.unique_blobs = set()
    for nodes in self.G.get_topsort():
      for top in nodes.get_layer().top:
        self.unique_blobs.add(top)

    old_to_new_tensor_name_mapping = {}

    for nodes in self.G.get_topsort():

      bottom_list = nodes.get_layer().bottom
      top_list = nodes.get_layer().top
      renamed_top = False
      new_top_list = []
      for top in top_list:
        if top in bottom_list:
          new_top = self.get_new_blob_name(nodes.get_layer().name)
          new_top_list.append((new_top, True)) # True indicates the blob name is new
          renamed_top = True
        else:
          new_top_list.append((top, False)) # False indicates that the blob name is old

      new_bottom_list = []
      renamed_bottom = False
      for bottom in bottom_list:
        if bottom in old_to_new_tensor_name_mapping:
          # We look at the last blob name in the old_to_new_tensor_name_mapping[bottom] list because layers are topologically sorted and the top blob going into the bottom of this layer has to be the one that was last encountered and renamed.
          new_bottom_list.append(old_to_new_tensor_name_mapping[bottom][-1])
          renamed_bottom = True
        else:
          new_bottom_list.append(bottom)
      if renamed_bottom:
        nodes.ClearField("bottom")
        for new_bottom in new_bottom_list:
          nodes.bottom.append(new_bottom)
      # Updating old_to_new_tensor_name_mapping if a top blob was renamed
      if renamed_top:
        nodes.ClearField("top")
        for pos, (top, is_new) in enumerate(new_top_list):
          if is_new:
            if top_list[pos] not in old_to_new_tensor_name_mapping:
              old_to_new_tensor_name_mapping[top_list[pos]] = []
            old_to_new_tensor_name_mapping[top_list[pos]].append(top)
          nodes.top.append(top)
