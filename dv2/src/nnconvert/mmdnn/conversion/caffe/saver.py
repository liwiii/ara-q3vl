import caffe
from dv_logging import get_logger
import subprocess
import sys

logger = get_logger(__name__, 'DVSAVR')


def save_model(MainModel, network_filepath, weight_filepath, dump_filepath):
  dump_net = dump_filepath + '.prototxt'
  dump_weight = dump_filepath + '.caffemodel'
  python_path = network_filepath + '.py'
  dump_net = str(dump_net)
  dump_weight = str(dump_weight)
  try:
    args = [str(sys.executable), python_path, '-w', weight_filepath, '-p', dump_net, '-m', dump_weight]

    path_list = list()
    added = set()
    for p in sys.path:
      if p not in added:
        path_list.append(p)
        added.add(p)
    all_paths = ':'.join(path_list)
    args_string = "export PYTHONPATH=" + all_paths + " && "

    args_string = args_string + ' '.join(args)
    result = subprocess.run(args_string, shell=True)
    code = result.returncode

    if code == 0:
      logger.info('caffe model files are saved as [ %s ] and [ %s ], generated by [ %s.py ] and [ %s ]', dump_net, dump_weight, network_filepath, weight_filepath)
      return 0
    return -1
  except Exception as e:
    logger.error("Exception while running generated code %s", str(e))
    return -1
